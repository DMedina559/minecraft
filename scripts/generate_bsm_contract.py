"""Generate the Minecraft operation catalog from BSM's exported OpenAPI JSON."""

import argparse
import json
from pathlib import Path


def generate(schema):
    operations = {}

    def content(value):
        return {
            media: item.get("schema", {})
            for media, item in value.get("content", {}).items()
        }

    for path, item in schema["paths"].items():
        for method, operation in item.items():
            if method not in {
                "get",
                "post",
                "put",
                "patch",
                "delete",
                "head",
                "options",
            }:
                continue
            operation_id = operation["operationId"]
            if operation_id in operations:
                raise ValueError(f"Duplicate operation ID: {operation_id}")
            operations[operation_id] = {
                "method": method.upper(),
                "path": path,
                "summary": operation.get("summary", ""),
                "tags": operation.get("tags", []),
                "parameters": item.get("parameters", [])
                + operation.get("parameters", []),
                "request": {
                    "required": operation.get("requestBody", {}).get("required", False),
                    "content": content(operation.get("requestBody", {})),
                },
                "responses": {
                    code: {"content": content(response)}
                    for code, response in operation.get("responses", {}).items()
                },
            }
    models = schema.get("components", {}).get("schemas", {})
    return "// Generated by scripts/generate_bsm_contract.py; do not edit.\n" + "".join(
        f'export const {name}={json.dumps(value, separators=(",", ":"), sort_keys=True)};\n'
        for name, value in [("operations", operations), ("models", models)]
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="JSON exported by bedrock_server_manager.web.contract")
    parser.add_argument("--check", action="store_true", help="Fail if the bundled catalog differs")
    args = parser.parse_args()
    output = Path(__file__).resolve().parents[1] / "addons/bsm_api_client/raw/scripts/core/contract.js"
    value = generate(json.loads(args.source.read_text(encoding="utf-8")))
    if args.check:
        if output.read_text(encoding="utf-8") != value:
            raise SystemExit("Minecraft contract drift. Run scripts/generate_bsm_contract.py with the backend export.")
    else:
        output.write_text(value, encoding="utf-8")


if __name__ == "__main__":
    main()
