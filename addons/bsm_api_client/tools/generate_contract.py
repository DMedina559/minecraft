"""Generate the Minecraft operation catalog from BSM's exported OpenAPI JSON."""

import json
import sys
from pathlib import Path


def generate(schema):
    operations = {}

    def content(value):
        return {
            media: item.get("schema", {})
            for media, item in value.get("content", {}).items()
        }

    for path, item in schema["paths"].items():
        for method, operation in item.items():
            if method not in {
                "get",
                "post",
                "put",
                "patch",
                "delete",
                "head",
                "options",
            }:
                continue
            operation_id = operation["operationId"]
            if operation_id in operations:
                raise ValueError(f"Duplicate operation ID: {operation_id}")
            operations[operation_id] = {
                "method": method.upper(),
                "path": path,
                "summary": operation.get("summary", ""),
                "tags": operation.get("tags", []),
                "parameters": item.get("parameters", [])
                + operation.get("parameters", []),
                "request": {
                    "required": operation.get("requestBody", {}).get("required", False),
                    "content": content(operation.get("requestBody", {})),
                },
                "responses": {
                    code: {"content": content(response)}
                    for code, response in operation.get("responses", {}).items()
                },
            }
    models = schema.get("components", {}).get("schemas", {})
    return "// Generated by tools/generate_contract.py; do not edit.\n" + "".join(
        f'export const {name}={json.dumps(value, separators=(",", ":"), sort_keys=True)};\n'
        for name, value in [("operations", operations), ("models", models)]
    )


if __name__ == "__main__":
    output = Path(__file__).resolve().parents[1] / "raw/scripts/core/contract.js"
    output.write_text(
        generate(json.loads(Path(sys.argv[1]).read_text())) + "", encoding="utf-8"
    )
